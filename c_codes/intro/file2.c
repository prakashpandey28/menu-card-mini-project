#include<stdio.h>

int main()
{
    // datatypes var_name;
    char ch = 's';
    int num=3;
    float fnum=2.2;
    double dnum=21.22;

    printf("ch is -> %c\n",ch);
    printf("num is -> %d\n",num);
    printf("fnum is -> %g\n",fnum);
    printf("dnum is -> %g\n",dnum);

    return 0;
    
}